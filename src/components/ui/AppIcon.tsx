interface AppIconProps {
  name: string;
  size?: number;
  color?: string;
  strokeWidth?: number;
  style?: any;
}

export const AppIcon: React.FC<AppIconProps> = ({
  name,
  size = 24,
  color = '#14212B',
  strokeWidth = 2,
  style,
}) => {
  const IconComponent =
    iconMap[name?.toLowerCase?.() || ''] || iconMap[name || ''] || Circle;

  return (
    <IconComponent
      size={size}
      color={color}
      strokeWidth={strokeWidth}
      style={style}
    />
  );
};

interface Icon3DProps {
  name: string;
  size?: number;
  color?: string;
  bgColor?: string;
  containerSize?: number;
  borderRadius?: number;
  showShadow?: boolean;
}

export const Icon3D: React.FC<Icon3DProps> = ({
  name,
  size = 24,
  color = '#FFFFFF',
  bgColor = '#0B6E84',
  containerSize = 44,
  borderRadius = 12,
  showShadow = true,
}) => {
  return (
    <View
      style={{
        width: containerSize,
        height: containerSize,
        borderRadius,
        backgroundColor: bgColor,
        alignItems: 'center',
        justifyContent: 'center',
        shadowColor: showShadow ? '#000' : 'transparent',
        shadowOffset: { width: 0, height: 2 },
        shadowOpacity: 0.2,
        shadowRadius: 4,
        elevation: showShadow ? 4 : 0,
      }}
    >
      <AppIcon name={name} size={size} color={color} />
    </View>
  );
};

